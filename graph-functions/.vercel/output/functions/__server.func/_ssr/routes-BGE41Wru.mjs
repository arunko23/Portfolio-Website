/** Construction polyline from the bottom transfer up to the selected PA. */
function middleConstructionPath(bottomX, pa) {
	const s = midFamilyIndex(bottomX);
	const yTop = yPA(pa);
	const pts = [];
	const y0 = CHART.midBottom;
	const y1 = Math.min(y0, Math.max(CHART.midTop, yTop));
	const step = y1 <= y0 ? -1 : 1;
	for (let y = y0; step < 0 ? y >= y1 : y <= y1; y += step) pts.push({
		x: xMiddleAtY(s, y),
		y
	});
	if (pts.length === 0 || pts[pts.length - 1].y !== yTop) pts.push({
		x: xMiddleAtY(s, yTop),
		y: yTop
	});
	return pts;
}
